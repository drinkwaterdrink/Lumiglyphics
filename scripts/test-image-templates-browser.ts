import { chromium } from "playwright";
import assert from "node:assert/strict";
const build = await Bun.build({ entrypoints: ["scripts/settings-browser-fixture.ts"], target: "browser" });
assert.equal(build.success, true, String(build.logs));
const bundle = await build.outputs[0]!.text();
const server = Bun.serve({ hostname: "127.0.0.1", port: 0, fetch: r => new URL(r.url).pathname === "/fixture.js" ? new Response(bundle, { headers: { "Content-Type": "application/javascript" } }) : new Response('<html><body style="margin:0"><script type="module" src="/fixture.js"></script></body></html>', { headers: { "Content-Type": "text/html" } }) });
const browser = await chromium.launch({ headless: true });
try {
  const page = await browser.newPage({ viewport: { width: 390, height: 844 } });
  await page.goto(`http://127.0.0.1:${server.port}/?setupDone&noSpeech`);
  const settings = page.locator("[data-vn-settings]");
  await page.evaluate(() => (window as any).settingsFixture.panel.openPage("templates"));
  assert.equal(await settings.getByLabel("Default template").locator('option[value="ensemble"]').count(),1);
  assert.equal(await settings.getByLabel("Full scene / ensemble in dynamic mode").isChecked(),false);
  assert.equal(await settings.getByRole("button", { name: "Add manga page", exact: true }).count(), 0);
  // Simulate the pre-Manga saved catalog without erasing user wording.
  await page.evaluate(() => { const f = (window as any).settingsFixture; f.config = { ...f.config, imageTemplates: f.config.imageTemplates.filter((t: any) => t.id !== "manga-page") }; f.panel.setConfig(f.config); });
  assert.equal(await settings.getByLabel("Default template").locator('option[value="manga-page"]').count(), 1);
  assert.equal(await settings.getByLabel("Manga page in dynamic mode").isChecked(), false);
  await settings.getByLabel("Default template", { exact: true }).selectOption("manga-page");
  assert.equal(await page.evaluate(() => (window as any).settingsFixture.config.defaultImageTemplateId), "manga-page");
  await settings.getByLabel("Choose templates from story context").check();
  assert.equal(await page.evaluate(() => (window as any).settingsFixture.config.dynamicImageTemplates), true);
  await settings.getByLabel("Manga page in dynamic mode").check();
  await settings.getByRole("button", { name: "Save templates", exact: true }).click();
  assert.equal(await page.evaluate(() => (window as any).settingsFixture.config.imageTemplates.find((t: any) => t.id === "manga-page").enabled), true);
  await settings.getByLabel("Manga page in dynamic mode").uncheck();
  await settings.getByRole("button", { name: "Save templates", exact: true }).click();
  assert.equal(await page.evaluate(() => (window as any).settingsFixture.config.defaultImageTemplateId), "manga-page", "manual default remains independent of dynamic choices");
  await settings.getByLabel("Choose templates from story context").uncheck();
  assert.equal(await settings.locator('[data-template-fields]').first().isVisible(), false, "raw editors start collapsed");
  await page.screenshot({ path: ".cache/templates-settings-mobile.png", fullPage: true });
  await settings.locator('[data-open-template="environment"]').click();
  assert.equal(await settings.getByLabel("Template name").getAttribute("type"), "text");
  await settings.getByText("Composition and context guidance", { exact: true }).click();
  assert.equal(await settings.getByLabel("Reference policy").isDisabled(), true);
  const body = settings.getByLabel("Template positive prompt", { exact: true });
  await body.fill("cinematic {{scene}} {{composition}}");
  await page.evaluate(() => { const f = (window as any).settingsFixture; f.panel.setConfig(structuredClone(f.config)); });
  assert.equal(await body.inputValue(), "cinematic {{scene}} {{composition}}");
  await body.fill("{{unsupported}}");
  const before = await page.evaluate(() => (window as any).settingsFixture.patches.length);
  await settings.getByRole("button", { name: "Save templates", exact: true }).click();
  assert.equal(await page.evaluate(() => (window as any).settingsFixture.patches.length), before);
  assert.match(await settings.locator('[data-template-status]').innerText(), /placeholder/i);
  await body.fill("cinematic {{scene}}");
  await settings.getByRole("button", { name: "Save templates", exact: true }).click();
  assert.equal(await page.evaluate(() => (window as any).settingsFixture.config.imageTemplates.find((t: any) => t.id === "environment").positive), "cinematic {{scene}}");
  await body.fill("failed save draft {{scene}}");
  await page.evaluate(() => { const f = (window as any).settingsFixture; f.ackMode = "manual"; f.panel.options.onSave = (patch: any,requestId?:string) => {f.patches.push(patch);f.saveRequests.push({patch,requestId});}; });
  await settings.getByRole("button", { name: "Save templates", exact: true }).click();
  await page.evaluate(() => { const f = (window as any).settingsFixture; f.panel.setSaveStatus({ kind: "error", error: "offline" },f.saveRequests.at(-1).requestId); f.panel.setConfig(f.config); });
  assert.equal(await body.inputValue(), "failed save draft {{scene}}");
  assert.match(await settings.locator('[data-template-status]').innerText(), /offline/);
  await settings.getByRole("button", { name: "Discard template changes", exact: true }).click();
  assert.equal(await body.inputValue(), "cinematic {{scene}}");
  await settings.getByRole("button", { name: "Duplicate template", exact: true }).click();
  assert.match(await settings.getByLabel("Template name").inputValue(), /copy/i);
  await settings.getByRole("button", { name: "Delete template", exact: true }).click();
  assert.equal(await settings.locator("[data-open-template]").count(), 7);
  assert.equal(await settings.evaluate(el => el.scrollWidth <= el.clientWidth + 1), true);
  await page.setViewportSize({ width: 1000, height: 900 });
  await page.goto(`http://127.0.0.1:${server.port}/?setupDone&noSpeech`);
  await page.evaluate(() => (window as any).settingsFixture.panel.openPage("templates"));
  await settings.getByLabel("Prompt format").selectOption("tags");
  assert.equal(await page.evaluate(() => (window as any).settingsFixture.config.imagePromptFormat), "tags");
  await page.evaluate(() => (window as any).settingsFixture.panel.openPage("style"));
  await settings.locator('[name="promptPrefix"]').fill("");
  await settings.locator('[data-apply]').click();
  assert.equal(await page.evaluate(() => (window as any).settingsFixture.config.promptPrefix), "");
  assert.equal(await settings.locator('[name="promptPrefix"]').count(), 1);
  await page.evaluate(() => (window as any).settingsFixture.panel.openPage("templates"));
  await settings.locator('[data-open-template="portrait"]').click();
  await settings.evaluate(el => { (el as HTMLElement).style.setProperty("--lumiverse-bg-elevated", "#ffffff"); (el as HTMLElement).style.setProperty("--lumiverse-text", "#222222"); });
  assert.equal(await settings.getByLabel("Template name").evaluate(el => getComputedStyle(el).backgroundColor), "rgb(255, 255, 255)");
  assert.equal(await settings.getByLabel("Template name").evaluate(el => getComputedStyle(el).color), "rgb(34, 34, 34)");
  await page.evaluate(() => { const f = (window as any).settingsFixture; f.config = { ...f.config, imageTemplates: [...Array.from({ length: 31 }, (_, i) => ({ ...f.config.imageTemplates[0], id: `saved-${i}` })), f.config.imageTemplates.find((t: any) => t.id === "manga-page")] }; f.panel.setConfig(f.config); });
  await settings.getByRole("button", { name: "Duplicate template", exact: true }).click();
  assert.equal(await settings.locator("[data-open-template]").count(), 32);
  assert.match(await settings.locator('[data-template-status]').innerText(), /32 templates/);
  assert.equal(await page.evaluate(() => (window as any).settingsFixture.previews), 0);
  console.log("image template browser checks passed");
} finally { await browser.close(); server.stop(true); }

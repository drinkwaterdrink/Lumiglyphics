// Generates docs/STATUS-TABLE.md from the repository itself so that counts in
// documentation cannot drift from the code. CI regenerates it and fails when the
// committed file is stale. Run with: bun run status:generate
import {readFileSync, readdirSync, statSync, writeFileSync} from 'node:fs';
import {join, relative} from 'node:path';

const root = join(import.meta.dir, '..');
const read = (path: string) => readFileSync(join(root, path), 'utf8');

function walk(dir: string, out: string[] = []): string[] {
  for (const name of readdirSync(join(root, dir))) {
    const rel = join(dir, name);
    if (statSync(join(root, rel)).isDirectory()) walk(rel, out);
    else out.push(rel);
  }
  return out;
}

/** Extracts the string literals of an exported array such as THEME_PRESET_IDS. */
function arrayLiterals(source: string, name: string): string[] {
  const match = source.match(new RegExp(`export const ${name}\\s*=\\s*\\[([\\s\\S]*?)\\]\\s*(as const)?;`));
  if (!match) throw new Error(`Could not find ${name}`);
  return [...match[1].matchAll(/["']([^"']+)["']/g)].map(m => m[1]);
}

/** Extracts the members of z.enum([...]) inside a named schema property. */
function enumLiterals(source: string, property: string): string[] {
  const match = source.match(new RegExp(`${property}:z\\.enum\\(\\[([\\s\\S]*?)\\]\\)`));
  if (!match) throw new Error(`Could not find enum ${property}`);
  return [...match[1].matchAll(/['"]([^'"]+)['"]/g)].map(m => m[1]);
}

const pkg = JSON.parse(read('package.json')) as {version: string; scripts: Record<string, string>};
const files = walk('src').concat(walk('scripts'));
const tsFiles = files.filter(f => f.endsWith('.ts') && !f.endsWith('.d.ts'));
const testFiles = tsFiles.filter(f => /\.test\.ts$/.test(f) && f.startsWith('src'));
const sourceFiles = tsFiles.filter(f => f.startsWith('src') && !/\.test\.ts$/.test(f));
const sourceLines = sourceFiles.reduce((total, f) => total + read(f).split('\n').length, 0);
const browserSuites = Object.keys(pkg.scripts).filter(name => name.startsWith('test:'));
const presets = arrayLiterals(read('src/config.ts'), 'THEME_PRESET_IDS');
const imageFamilies = enumLiterals(read('src/shared/image-prompt-profile.ts'), 'family');
const spindle = JSON.parse(read('spindle.json')) as {version?: string; permissions?: unknown[]};

const rows: Array<[string, string]> = [
  ['Extension version', pkg.version],
  ['Theme presets', String(presets.length)],
  ['Image prompt families', String(imageFamilies.length)],
  ['Source files (non-test, src/)', String(sourceFiles.length)],
  ['Source lines (non-test, src/)', sourceLines.toLocaleString('en-US')],
  ['Unit test files (src/)', String(testFiles.length)],
  ['Browser suite scripts (test:*)', String(browserSuites.length)],
  ['Declared Spindle permissions', spindle.permissions ? String(spindle.permissions.length) : 'not declared'],
];

const body = [
  '# Status table (generated)',
  '',
  'Generated by `bun run status:generate` from the repository. Do not edit by hand; CI fails when this file is stale.',
  'Test counts here are file counts. The live test count appears in the `bun test` output.',
  '',
  '| Measure | Value |',
  '|---|---|',
  ...rows.map(([label, value]) => `| ${label} | ${value} |`),
  '',
  `Theme presets: ${presets.map(p => `\`${p}\``).join(', ')}.`,
  '',
  `Image prompt families: ${imageFamilies.map(p => `\`${p}\``).join(', ')}.`,
  '',
].join('\n');

const outPath = join(root, 'docs/STATUS-TABLE.md');
writeFileSync(outPath, body);
console.log(`Wrote ${relative(root, outPath)}`);

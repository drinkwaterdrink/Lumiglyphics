import { chromium } from "playwright";
import assert from "node:assert/strict";
import { mkdir } from "node:fs/promises";
const build = await Bun.build({ entrypoints: ["scripts/settings-browser-fixture.ts"], target: "browser" });
assert.ok(build.success, String(build.logs));
const bundle = await build.outputs[0]!.text();
const server = Bun.serve({ hostname: "127.0.0.1", port: 0, fetch: request => new URL(request.url).pathname === "/fixture.js" ? new Response(bundle, { headers: { "Content-Type": "application/javascript" } }) : new Response('<html><head><meta name="viewport" content="width=device-width, initial-scale=1"></head><body style="margin:0"><script type="module" src="/fixture.js"></script></body></html>', { headers: { "Content-Type": "text/html" } }) });
const browser = await chromium.launch({ headless: true });
try {
  const page = await browser.newPage({ viewport: { width: 390, height: 844 } });
  await page.goto(`http://127.0.0.1:${server.port}/?setupDone&noSpeech`);
  const settings = page.locator('[data-vn-settings]');
  await page.evaluate(() => (window as any).settingsFixture.panel.openPage('style'));
  const select = settings.getByLabel('Prompt preset', { exact: true });
  assert.equal(await select.locator('option').count(), 13);
  const before = await page.evaluate(() => (window as any).settingsFixture.patches.length);
  await select.selectOption('builtin-style:phone-candid');
  const prefix = settings.locator('[name="promptPrefix"]');
  const suffix = settings.locator('[name="promptSuffix"]');
  assert.match(await prefix.inputValue(), /cellphone/);
  assert.match(await suffix.inputValue(), /JPEG/);
  assert.equal(await page.evaluate(() => (window as any).settingsFixture.patches.length), before, 'selecting a style does not silently apply or request an image');
  assert.match(await settings.locator('[data-style-description]').innerText(), /handheld/);
  await suffix.fill('Subtle phone grain; keep faces readable.');
  await settings.getByLabel('Preset name', { exact: true }).fill('My phone look');
  await settings.getByRole('button', { name: 'Save preset', exact: true }).click();
  const personal = await page.evaluate(() => (window as any).settingsFixture.config.promptPresets[0]);
  assert.equal(personal.suffix, 'Subtle phone grain; keep faces readable.');
  const snapshot = await page.evaluate(() => (window as any).settingsFixture.config);
  assert.notEqual(snapshot.promptSuffix, personal.suffix, 'library save is distinct from Apply');
  await select.selectOption('builtin-style:anime');
  await select.selectOption(personal.id);
  assert.equal(await suffix.inputValue(), personal.suffix, 'personal style restores its suffix');
  await settings.locator('[data-apply-bar]').click();
  assert.equal(await page.evaluate(() => (window as any).settingsFixture.config.promptSuffix), personal.suffix);
  await select.selectOption('builtin-style:neutral');
  assert.equal(await suffix.inputValue(), '', 'explicit empty style clears finishing details');
  await settings.getByRole('button', { name: 'Delete', exact: true }).click();
  assert.equal(await select.locator('option[value="builtin-style:neutral"]').count(), 1, 'built-ins cannot be deleted');
  await select.selectOption('builtin-style:hunter-hand-drawn');
  assert.match(await prefix.inputValue(), /Hunter x Hunter/);
  assert.equal(await page.evaluate(() => (window as any).settingsFixture.previews), 0);
  await mkdir('.cache/shared-styles', { recursive: true });
  await page.screenshot({ path: '.cache/shared-styles/mobile.png', fullPage: true });
  await page.close();
  console.log('shared styles browser checks passed');
} finally { await browser.close(); server.stop(true); }


import { chromium } from "playwright";
import assert from "node:assert/strict";
const build = await Bun.build({ entrypoints: ["scripts/image-review-browser-fixture.ts"], target: "browser" });
assert.equal(build.success, true, String(build.logs));
const bundle = await build.outputs[0]!.text();
const server = Bun.serve({ hostname: "127.0.0.1", port: 0, fetch: (request) => new URL(request.url).pathname === "/fixture.js" ? new Response(bundle, { headers: { "Content-Type": "application/javascript" } }) : new Response('<html><body style="margin:0"><script type="module" src="/fixture.js"></script></body></html>', { headers: { "Content-Type": "text/html" } }) });
const browser = await chromium.launch({ headless: true });
try {
  const page = await browser.newPage({ viewport: { width: 390, height: 844 } });
  await page.goto(`http://127.0.0.1:${server.port}`);
  const studio = page.locator("[data-image-studio]");
  await studio.getByRole("button", { name: /Image prompts/ }).click();
  assert.equal(await studio.getByLabel("Review before generating").isChecked(), true);
  await studio.getByLabel("Review before generating").uncheck();
  assert.deepEqual(await page.evaluate(() => (window as any).imageFixture.actions.at(-1)), { reviewImages: false });
  const prompt = studio.getByLabel("Positive prompt", { exact: true });
  await prompt.fill("edited portrait");
  await page.evaluate(() => { const f = (window as any).imageFixture; f.studio.setTurn(structuredClone(f.turn)); });
  assert.equal(await prompt.inputValue(), "edited portrait", "host refresh preserves unsaved draft");
  await studio.locator("summary").click();
  await studio.getByLabel("Parameters (JSON)").fill('{"seed":99}');
  await studio.getByRole("button", { name: "Generate this", exact: true }).click();
  assert.equal(await studio.getByRole("button", { name: "Generate this", exact: true }).isDisabled(), true);
  const action = await page.evaluate(() => (window as any).imageFixture.actions.at(-1));
  assert.equal(action.type, "vn_image_review");
  assert.equal(action.edits.prompt, "edited portrait");
  assert.equal(action.edits.parameters.seed, 99);
  await page.evaluate(() => { const f = (window as any).imageFixture; f.turn.imageRequests[0].state = "approved"; f.turn.assets[0].status = "generated"; f.studio.setTurn(f.turn); });
  assert.equal(await prompt.isEditable(), false);
  await studio.getByRole("button", { name: "Prepare replacement" }).click();
  assert.equal((await page.evaluate(() => (window as any).imageFixture.actions.at(-1))).type, "vn_prepare_image");
  await page.evaluate(() => { const f = (window as any).imageFixture; f.turn.imageRequests[0].requestId = "skip-request"; f.turn.imageRequests[0].state = "review"; f.turn.assets[0].status = "generating"; f.studio.setTurn(f.turn); });
  await studio.getByLabel("Parameters (JSON)").fill('{ unfinished');
  await studio.getByRole("button", { name: "Skip", exact: true }).click();
  assert.equal((await page.evaluate(() => (window as any).imageFixture.actions.at(-1))).action, "skip", "Skip ignores unfinished edits");
  await page.evaluate(() => { const f = (window as any).imageFixture; f.turn.imageRequests = []; f.turn.assets[0].status = "generated"; f.studio.setTurn(f.turn); });
  assert.match(await studio.locator("section").innerText(), /original request is unavailable/i);
  assert.equal(await page.locator("script").count(), 1, "prompt text never creates executable elements");
  await page.evaluate(() => {
    const f = (window as any).imageFixture;
    f.turn.paragraphs.push("Mira watches the rain through the library window.");
    f.turn.assets.push({ jobId: "job-2", paragraphIndex: 1, status: "generating" });
    f.turn.imageRequests = [{ requestId: "next-request", jobId: "job-2", paragraphIndex: 1, state: "review", prompt: "Mira, silver hair, green eyes, red coat, beside a library window, soft afternoon light, rain outside, one person, medium shot", negativePrompt: "blurry, text, watermark", model: "Selected image model", provider: "NanoGPT", connectionId: "nano", parameters: { seed: 42, aspect_ratio: "16:9" }, referenceSummary: "No extension reference", createdAt: "now" }];
    f.studio.setTurn(f.turn); f.studio.setCursor(1);
  });
  await studio.getByRole("button", { name: /Image prompts/ }).click();
  await studio.getByRole("button", { name: /Image prompts/ }).click();
  assert.equal(await studio.getByLabel("Picture", { exact: true }).inputValue(), "job-2", "opening inspector follows reading cursor");
  await page.screenshot({ path: ".cache/image-review-mobile.png" });
  await page.setViewportSize({ width: 1440, height: 960 });
  await page.screenshot({ path: ".cache/image-review-desktop.png" });
  console.log("image review browser checks passed");
} finally { await browser.close(); server.stop(true); }

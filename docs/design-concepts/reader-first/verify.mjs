import {chromium} from 'playwright';
import assert from 'node:assert/strict';

// Start a static server for this directory first. Optional custom Chromium path
// is useful in sandboxes; standard Playwright installations need no override.
const url=process.env.CONCEPT_URL||'http://127.0.0.1:4174';
const screenshots=new URL('./',import.meta.url).pathname;
const browser=await chromium.launch({headless:true,...(process.env.CONCEPT_CHROMIUM_PATH?{executablePath:process.env.CONCEPT_CHROMIUM_PATH}:{}),args:['--no-sandbox','--disable-dev-shm-usage']});
const errors=[];
let checks=0;
const check=(value,message)=>{assert.ok(value,message);checks++};
try{
 const page=await browser.newPage({viewport:{width:1440,height:1000},deviceScaleFactor:1});
 page.on('pageerror',e=>errors.push(e.message));
 await page.goto(url);await page.locator('.scene').evaluate(async el=>{const src=getComputedStyle(el).backgroundImage.slice(5,-2);const img=new Image();img.src=src;await img.decode()});
 check(await page.title()==='Lumiglyphics · Reader-first design concept','Page is labeled as concept');
 check(await page.locator('#passage').textContent().then(x=>x.includes('every place worth finding')),'Opening passage renders');
 await page.screenshot({path:screenshots+'preview-desktop.png'});
 await page.getByRole('button',{name:'Story',exact:true}).click();
 await page.getByRole('tab',{name:'Documents',exact:true}).click();
 check(await page.locator('#workspace-content').textContent().then(x=>x.includes('No documents discovered yet')),'Unreached document is absent');
 await page.getByRole('tab',{name:'People',exact:true}).click();await page.getByRole('tab',{name:'People',exact:true}).press('ArrowRight');
 check(await page.getByRole('tab',{name:'Places',exact:true}).getAttribute('aria-selected')==='true','Tabs support arrow keys');
 await page.getByRole('tab',{name:'People',exact:true}).click();
 await page.screenshot({path:screenshots+'preview-workspace.png'});
 await page.getByRole('button',{name:'Meet Mira',exact:false}).click();
 await page.keyboard.press('Escape');
 check(await page.getByRole('tab',{name:'People',exact:true}).isVisible(),'Escape backs out one detail layer');
 await page.keyboard.press('Escape');check(await page.locator('#workspace').isHidden(),'Second Escape closes workspace');
 check(await page.evaluate(()=>document.activeElement?.dataset.view)==='story','Panel restores opener focus');
 await page.getByRole('button',{name:'Save this moment',exact:true}).click();
 await page.getByRole('button',{name:'Moment saved; open saved moments',exact:true}).click();
 check(await page.locator('.moment-quote').textContent().then(x=>x.includes('every place worth finding')),'Saved moment uses the actual selected passage');
 await page.getByRole('button',{name:'Add a personal note',exact:false}).click();
 await page.locator('#caption-input').fill('<script>not executable</script>');
 await page.getByRole('button',{name:'Keep note in this preview',exact:false}).click();
 check(await page.locator('#workspace-content').textContent().then(x=>x.includes('<script>not executable</script>')),'User note remains plain text');
 check(await page.locator('#workspace-content script').count()===0,'Note cannot inject script elements');
 await page.getByRole('button',{name:'Return to passage',exact:false}).click();
 check(await page.locator('#counter').textContent().then(x=>x.includes('01')),'Saved source returns to its actual paragraph');
 await page.getByRole('button',{name:'Continue',exact:true}).click();
 await page.locator('.entity-link').click();
 check(await page.locator('#workspace-content').textContent().then(x=>x.includes('Only the visible fragment')),'Document includes disclosure explanation');
 await page.getByRole('button',{name:'Close panel and return to reader',exact:true}).click();
 await page.getByRole('button',{name:'Settings',exact:true}).click();
 const initialSize=await page.locator('#passage').evaluate(el=>parseFloat(getComputedStyle(el).fontSize));
 await page.getByRole('button',{name:'Increase text size'}).click();
 check(await page.locator('#passage').evaluate(el=>parseFloat(getComputedStyle(el).fontSize))===initialSize+1,'Text size preview updates actual reader');
 await page.getByRole('switch',{name:'Reduced motion',exact:true}).click();
 check(await page.locator('body').evaluate(el=>el.classList.contains('reduced-motion')),'Motion preference applies');
 await page.getByRole('button',{name:'Close panel and return to reader'}).click();
 await page.getByRole('button',{name:'Search menus and actions'}).click();
 await page.locator('#command-input').fill('artwork');await page.locator('#command-input').press('Enter');
 check(await page.locator('#workspace-title').textContent()==='Artwork','Search Enter opens matching destination');
 await page.getByRole('button',{name:'Approve preview',exact:false}).click();
 check(await page.locator('#art-status').isHidden(),'Approval clears sample review attention');
 await page.getByRole('button',{name:'Close panel and return to reader'}).click();
 await page.getByRole('button',{name:'Focus reading',exact:true}).click();
 check(await page.locator('.rail').isHidden(),'Focus reading hides navigation');
 await page.getByRole('button',{name:'Show navigation',exact:false}).click();
 check(await page.locator('.rail').isVisible(),'Focus mode is reversible');
 // Reach a local reply and verify editing persists through navigation.
 for(let i=0;i<2;i++)await page.getByRole('button',{name:'Continue',exact:true}).click();
 await page.getByRole('button',{name:'Your reply',exact:false}).click();
 await page.locator('#reply-draft').fill('My local, unsent intention.');
 await page.getByRole('button',{name:'Settings',exact:true}).click();
 await page.getByRole('button',{name:'Close panel and return to reader'}).click();
 await page.getByRole('button',{name:'Your reply',exact:false}).click();
 check(await page.locator('#reply-draft').inputValue()==='My local, unsent intention.','Draft survives surface switches');
 await page.close();
 const phone=await browser.newPage({viewport:{width:390,height:844},isMobile:true,hasTouch:true,deviceScaleFactor:1});
 phone.on('pageerror',e=>errors.push(e.message));await phone.goto(url);await phone.locator('.scene').waitFor();
 check(await phone.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'Phone has no horizontal overflow');
 await phone.screenshot({path:screenshots+'preview-mobile.png'});
 await phone.getByRole('button',{name:'Story',exact:true}).click();
 check(await phone.locator('#reader').evaluate(el=>el.inert),'Mobile workspace makes underlying reader inert');
 const box=await phone.locator('#workspace').boundingBox();
 check(box&&box.width===390&&box.y>=56&&box.y+box.height<=775,'Phone workspace fits between title and persistent navigation');
 await phone.screenshot({path:screenshots+'preview-mobile-workspace.png'});
 await phone.getByRole('button',{name:'Close panel and return to reader'}).click();
 check(await phone.locator('#reader').evaluate(el=>!el.inert),'Closing mobile workspace reactivates reader');
 await phone.getByRole('button',{name:'More',exact:true}).click();
 await phone.getByRole('button',{name:'Settings',exact:true}).filter({visible:true}).click();
 check(await phone.locator('#workspace-title').textContent()==='Settings','Phone More reaches Settings');
 await phone.setViewportSize({width:320,height:568});
 check(await phone.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'Small phone has no horizontal overflow');
 await phone.getByRole('button',{name:'Close panel and return to reader'}).click();
 const continueBox=await phone.getByRole('button',{name:'Continue',exact:true}).boundingBox();
 check(continueBox&&continueBox.height>=44,'Small-phone continue has a 44px target');
 const navBox=await phone.locator('.rail').boundingBox();
 check(navBox&&continueBox&&continueBox.y+continueBox.height<=navBox.y,'Continue stays above phone navigation');
 await phone.close();
 check(errors.length===0,`No browser errors: ${errors.join('; ')}`);
 console.log(`${checks} concept checks passed. Desktop and mobile screenshots updated.`);
}finally{await browser.close()}
